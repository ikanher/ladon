"""Ownership and quarantine controls for generated-goal scratch leases."""
from __future__ import annotations

import errno
import json
import os
import stat
import time
from pathlib import Path

import pytest

from ladon import _proof_contract_goal_scratch as scratch
from ladon.process_supervisor import ProcessResult
from ladon.proof_contract_obligation_supervision import _execute_job, _run


@pytest.fixture
def repo(tmp_path):
    root = tmp_path / 'repo'
    root.mkdir()
    return root


def _job(root, operation):
    return {'version': 1, 'operation': operation,
            'request': {'repoRoot': str(root)}}


@pytest.mark.parametrize(('module', 'operation'), sorted(scratch.GOAL_WORKERS))
def test_all_goal_worker_dispatches_receive_one_scoped_lease(
        repo, module, operation, monkeypatch):
    for key in scratch.ENV_KEYS:
        monkeypatch.setenv(key, 'attacker-selected-workspace')
    observed = {}

    def runner(command, **kwargs):
        observed.update(kwargs['env'])
        assert command[-1] == module
        assert all(key.encode() not in kwargs['input_bytes'] for key in scratch.ENV_KEYS)
        return ProcessResult(tuple(command), 0,
            '{"status":"completed","result":{"ok":true},"diagnostic":null}', '', 0.0)

    job = _job(repo, operation)
    state = {'receipt': None, 'inputDigest': None, 'bounds': None}
    result = _execute_job(job, {'timeout_seconds': 1, 'deadlineMonotonic': time.monotonic() + 10,
        'max_output_bytes': 1024, 'max_rss_bytes': 1024}, state, runner,
        worker_module=module)
    assert result['status'] == 'completed'
    metadata = json.loads(observed[scratch.ENV_WORKSPACE])
    assert metadata['root'] == str(repo)
    assert all(key not in observed for key in scratch.ENV_KEYS[1:])
    assert not (repo / '.ladon/correspondence' / metadata['name']).exists()


def test_non_goal_dispatch_does_not_provision_lease(repo):
    assert scratch.provision(_job(repo, 'extract-provider'),
                             'ladon.proof_contract_bridge_worker') is None
    assert not (repo / '.ladon').exists()


def test_every_worker_launch_strips_inherited_lease_metadata(monkeypatch, repo):
    for key in scratch.ENV_KEYS:
        monkeypatch.setenv(key, 'attacker-selected-workspace')
    observed = {}

    def runner(_command, **kwargs):
        observed.update(kwargs['env'])
        return ProcessResult(('fake-worker',), 0, '', '', 0.0)

    _run(b'{}', {'timeout_seconds': 1, 'deadlineMonotonic': time.monotonic() + 10,
                 'max_output_bytes': 8, 'max_rss_bytes': 10}, runner)
    assert all(key not in observed for key in scratch.ENV_KEYS)


def test_foreign_regular_goal_replacement_is_preserved_and_quarantined(repo):
    lease = scratch.provision(
        _job(repo, 'check-route-context-goal'),
        'ladon.proof_contract_route_context_worker')
    owner = {**lease, 'lease': lease, 'goalIdentity': None}
    goal = lease['path'] / scratch.GOAL_NAME
    scratch.write_goal(goal, '-- owned bytes\n', owner)
    goal.unlink()
    goal.write_text('-- foreign sentinel\n')

    with pytest.raises(OSError, match='replaced'):
        scratch.cleanup_worker_goal(owner)
    quarantine = Path(scratch.finish(lease))
    assert (quarantine / scratch.GOAL_NAME).read_bytes() == b'-- foreign sentinel\n'
    assert not goal.exists()


