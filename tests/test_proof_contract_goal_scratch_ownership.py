def test_missing_or_renamed_lease_fails_closed(repo):
    lease = scratch.provision(
        _job(repo, 'check-context-goal'), 'ladon.proof_contract_context_worker')
    moved = lease['path'].with_name('goal-renamed-by-other-owner')
    lease['path'].rename(moved)
    with pytest.raises(OSError):
        scratch.finish(lease)
    assert moved.is_dir()


def test_symlink_replacement_and_selected_root_replacement_are_preserved(repo, tmp_path):
    lease = scratch.provision(
        _job(repo, 'check-route-context-goal'),
        'ladon.proof_contract_route_context_worker')
    moved = lease['path'].with_name('goal-owned-moved')
    lease['path'].rename(moved)
    foreign = tmp_path / 'foreign-workspace'
    foreign.mkdir()
    sentinel = foreign / 'keep.txt'
    sentinel.write_text('foreign bytes')
    lease['path'].symlink_to(foreign, target_is_directory=True)
    with pytest.raises(OSError):
        scratch.finish(lease)
    assert lease['path'].is_symlink()
    assert sentinel.read_text() == 'foreign bytes'

    # A second lease binds the selected repository directory's inode as well.
    other = tmp_path / 'other-repo'
    other.mkdir()
    lease = scratch.provision(
        _job(other, 'check-context-goal'), 'ladon.proof_contract_context_worker')
    moved_root = other.with_name('repo-moved')
    other.rename(moved_root)
    other.mkdir()
    with pytest.raises(OSError, match='identity changed'):
        scratch.finish(lease)
    assert (moved_root / '.ladon/correspondence' / lease['name']).is_dir()


def test_quarantine_rename_failure_preserves_original_bytes(monkeypatch, repo):
    lease = scratch.provision(
        _job(repo, 'check-probe-goal'), 'ladon.proof_contract_probe_worker')
    goal = lease['path'] / scratch.GOAL_NAME
    goal.write_bytes(b'preserve-me')

    def fail_rename(*_args, **_kwargs):
        raise OSError(errno.EXDEV, 'synthetic cross-device refusal')

    monkeypatch.setattr(scratch.os, 'rename', fail_rename)
    with pytest.raises(OSError, match='cross-device refusal'):
        scratch.finish(lease)
    assert goal.read_bytes() == b'preserve-me'


def test_worker_refuses_lease_for_a_different_selected_repository(repo, tmp_path, monkeypatch):
    lease = scratch.provision(_job(repo, 'check-goal'), 'ladon.proof_contract_bridge_worker')
    other = tmp_path / 'other-repo' / '.ladon' / 'correspondence'
    other.mkdir(parents=True)
    monkeypatch.setenv(scratch.ENV_WORKSPACE, scratch.environment(lease)[scratch.ENV_WORKSPACE])
    try:
        with pytest.raises(OSError, match='different repository'), scratch.worker_workspace(other):
            pytest.fail('foreign lease was accepted')
    finally:
        scratch.finish(lease)


def test_oversized_observed_goal_is_preserved_without_hashing_it(repo, monkeypatch):
    lease = scratch.provision(_job(repo, 'check-goal'), 'ladon.proof_contract_bridge_worker')
    owner = {**lease, 'lease': lease, 'goalIdentity': None, 'goalDigest': None}
    goal = lease['path'] / scratch.GOAL_NAME
    scratch.write_goal(goal, '-- original', owner)
    with goal.open('r+b') as stream:
        stream.truncate(scratch.MAX_GOAL_BYTES + 1)
    monkeypatch.setattr(scratch.os, 'read', lambda *_args: pytest.fail('unbounded cleanup read'))
    with pytest.raises(OSError, match='byte bound'):
        scratch.cleanup_worker_goal(owner)
    quarantine = Path(scratch.finish(lease))
    assert (quarantine / scratch.GOAL_NAME).stat().st_size == scratch.MAX_GOAL_BYTES + 1


@pytest.mark.parametrize(('flag', 'expected_code'), [
    ('memory_limited', 'memory-limit'), ('timed_out', 'timeout'),
    (None, 'goal-scratch-cleanup-required'),
])
def test_cleanup_failure_keeps_stop_code_and_preserves_uncertain_material(
        repo, flag, expected_code):
    observed = {}

    def runner(command, **kwargs):
        metadata = json.loads(kwargs['env'][scratch.ENV_WORKSPACE])
        path = repo / '.ladon/correspondence' / metadata['name']
        sentinel = path / 'unowned.txt'
        sentinel.write_bytes(b'keep this')
        renamed = path.with_name('renamed-attempt')
        path.rename(renamed)
        observed['sentinel'] = renamed / sentinel.name
        options = {flag: True} if flag else {}
        return ProcessResult(tuple(command), 0,
            '{"status":"completed","result":{"ok":true},"diagnostic":null}', '', 0.0,
            **options)

    state = {'receipt': None, 'inputDigest': None, 'bounds': None}
    result = _execute_job(_job(repo, 'check-goal'), {
        'timeout_seconds': 1, 'deadlineMonotonic': time.monotonic() + 10,
        'max_output_bytes': 1024, 'max_rss_bytes': 1024}, state, runner,
        worker_module='ladon.proof_contract_bridge_worker')
    assert result['status'] == 'incomplete'
    assert result['diagnostic']['code'] == expected_code
    assert 'cleanup could not be verified' in result['diagnostic']['message']
    assert observed['sentinel'].read_bytes() == b'keep this'
    if flag == 'memory_limited':
        assert 'Stop progress and report back to user' in result['diagnostic']['message']


def test_fifo_replacement_is_preserved_without_blocking(repo):
    lease = scratch.provision(_job(repo, 'check-goal'), 'ladon.proof_contract_bridge_worker')
    owner = {**lease, 'lease': lease, 'goalIdentity': None, 'goalDigest': None}
    goal = lease['path'] / scratch.GOAL_NAME
    scratch.write_goal(goal, '-- original', owner)
    goal.unlink()
    os.mkfifo(goal)
    with pytest.raises(OSError, match='replaced'):
        scratch.cleanup_worker_goal(owner)
    quarantine = Path(scratch.finish(lease))
    assert stat.S_ISFIFO((quarantine / scratch.GOAL_NAME).lstat().st_mode)
